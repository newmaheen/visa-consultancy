        // ==========================================
        let animationFrameId = null;

        function launchFlight(event, serviceTitle = '') {
            const modal = document.getElementById('inquiryModal');
            const plane = document.getElementById('flyingPlane');
            const box = document.getElementById('flightBox');

            if (serviceTitle) {
                const serviceInput = document.getElementById('serviceTypeInput');
                for (let option of serviceInput.options) {
                    if (option.text.toLowerCase().includes(serviceTitle.toLowerCase()) || serviceTitle.toLowerCase().includes(option.text.toLowerCase())) {
                        option.selected = true;
                        break;
                    }
                }
            }

            let startX = window.innerWidth / 2;
            let startY = window.innerHeight * 0.7;
            if (event && event.clientX) {
                startX = event.clientX;
                startY = event.clientY;
            }

            const centerX = window.innerWidth / 2;
            const centerY = window.innerHeight / 2;

            box.classList.remove('box-visible');
            box.classList.add('box-hidden');
            modal.classList.remove('hidden');

            plane.style.opacity = '1';

            if (animationFrameId) cancelAnimationFrame(animationFrameId);

            const duration = 1800;
            const startTime = performance.now();
            let prevX = startX;
            let prevY = startY;

            function animateFlight(now) {
                const elapsed = now - startTime;
                const progress = Math.min(elapsed / duration, 1);

                let currentX, currentY;

                if (progress < 0.75) {
                    const loopProgress = progress / 0.75;
                    const angle = loopProgress * Math.PI * 2;

                    const radiusX = Math.min(window.innerWidth * 0.28, 300);
                    const radiusY = Math.min(window.innerHeight * 0.28, 220);

                    const blend = Math.sin((loopProgress * Math.PI) / 2);
                    const orbitCenterX = startX + (centerX - startX) * blend;
                    const orbitCenterY = startY + (centerY - startY) * blend;

                    currentX = orbitCenterX + Math.cos(angle - Math.PI / 2) * radiusX;
                    currentY = orbitCenterY + Math.sin(angle - Math.PI / 2) * radiusY;
                } else {
                    const exitProgress = (progress - 0.75) / 0.25;

                    if (!box.classList.contains('box-visible')) {
                        box.classList.remove('box-hidden');
                        box.classList.add('box-visible');
                    }

                    const exitTargetX = window.innerWidth + 200;
                    const exitTargetY = -200;

                    const easeSpeed = Math.pow(exitProgress, 2);
                    currentX = centerX + (exitTargetX - centerX) * easeSpeed;
                    currentY = (centerY - 80) + (exitTargetY - (centerY - 80)) * easeSpeed;
                }

                const dx = currentX - prevX;
                const dy = currentY - prevY;
                let rotationDeg = Math.atan2(dy, dx) * (180 / Math.PI) + 90;

                prevX = currentX;
                prevY = currentY;

                plane.style.left = `${currentX - 48}px`;
                plane.style.top = `${currentY - 48}px`;
                plane.style.transform = `rotate(${rotationDeg}deg)`;

                if (progress < 1) {
                    animationFrameId = requestAnimationFrame(animateFlight);
                } else {
                    plane.style.opacity = '0';
                }
            }

            animationFrameId = requestAnimationFrame(animateFlight);
        }

