        // ===============================================================
        // PART 5: RESPONSIVE CAROUSEL PAGINATION (Mobile: 2, Desktop: 6)
        // ===============================================================
        function getStoriesPerPage() {
            // Screen width 640px er kom (Mobile) hole 2 ti, ar boro screen-e 6 ti
            return window.innerWidth < 1024 ? 2 : 6;
        }

        let currentStoryPage = 1;

        function renderStoryPagination() {
            const cards = document.querySelectorAll('.story-card');
            const totalCards = cards.length;
            if (totalCards === 0) return;

            const storiesPerPage = getStoriesPerPage();
            const totalPages = Math.ceil(totalCards / storiesPerPage);

            // Page bounds validation
            if (currentStoryPage > totalPages) {
                currentStoryPage = totalPages;
            }

            const dotsContainer = document.getElementById('storyPageDots');
            const prevBtn = document.getElementById('prevStoryBtn');
            const nextBtn = document.getElementById('nextStoryBtn');
            const grid = document.getElementById('storyCardsGrid');

            if (grid) {
                grid.style.opacity = '0';
            }

            setTimeout(() => {
                cards.forEach((card, index) => {
                    const startIndex = (currentStoryPage - 1) * storiesPerPage;
                    const endIndex = startIndex + storiesPerPage;

                    if (index >= startIndex && index < endIndex) {
                        card.style.display = 'flex';
                    } else {
                        card.style.display = 'none';
                    }
                });

                if (grid) {
                    grid.style.opacity = '1';
                }
            }, 120);

            // Prev & Next button disable controller
            if (prevBtn && nextBtn) {
                prevBtn.disabled = currentStoryPage === 1;
                nextBtn.disabled = currentStoryPage === totalPages;
            }

            // Pagination Indicator Dots Generator
            if (dotsContainer) {
                dotsContainer.innerHTML = '';
                for (let i = 1; i <= totalPages; i++) {
                    const dot = document.createElement('button');
                    dot.type = 'button';
                    dot.className = `h-2 sm:h-3 rounded-full transition-all ${
                        i === currentStoryPage 
                        ? 'bg-emerald-400 w-6 sm:w-7' 
                        : 'bg-[#064e3b] w-2 sm:w-3 hover:bg-emerald-600'
                    }`;
                    dot.onclick = () => {
                        currentStoryPage = i;
                        renderStoryPagination();
                    };
                    dotsContainer.appendChild(dot);
                }
            }
        }

        function nextStoryPage() {
            const cards = document.querySelectorAll('.story-card');
            const storiesPerPage = getStoriesPerPage();
            const totalPages = Math.ceil(cards.length / storiesPerPage);
            if (currentStoryPage < totalPages) {
                currentStoryPage++;
                renderStoryPagination();
            }
        }

        function prevStoryPage() {
            if (currentStoryPage > 1) {
                currentStoryPage--;
                renderStoryPagination();
            }
        }

