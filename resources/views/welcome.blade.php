        function animateSingleBanner(row) {
            row.dataset.animated = 'true';
            const innerBox = row.querySelector('.banner-inner-box');
            if (!innerBox) return;

            const isFromLeft = row.dataset.direction === 'left';
            const startOffset = isFromLeft ? -window.innerWidth : window.innerWidth;

            innerBox.style.transform = `translateX(${startOffset}px)`;
            innerBox.style.opacity = '1';

            const towRig = document.createElement('div');
