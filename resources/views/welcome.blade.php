            document.body.appendChild(towRig);

            const duration = 1200;
            const startTime = performance.now();
            towRig.style.opacity = '1';

            function animate(now) {
                const elapsed = now - startTime;
                const progress = Math.min(elapsed / duration, 1);

                const ease = 1 - Math.pow(1 - progress, 3);
                const currentX = startOffset * (1 - ease);
                innerBox.style.transform = `translateX(${currentX}px)`;

                const rect = row.getBoundingClientRect();
                const rigY = rect.top + (rect.height / 2) - 30;
                let rigX = isFromLeft ? (rect.left + (rect.width * ease)) : (rect.left - 130 + (rect.width * (1 - ease)));

                towRig.style.left = `${rigX}px`;
                towRig.style.top = `${rigY}px`;

                if (progress < 1) {
                    requestAnimationFrame(animate);
                } else {
                    innerBox.style.transform = 'translateX(0px)';
                    towRig.style.opacity = '0';
                    setTimeout(() => {
                        towRig.remove();
                    }, 350);
                }
            }

            requestAnimationFrame(animate);
        }

