        // PART 3: AJAX APPLICATION FORM SUBMISSION
        // ==========================================
        document.getElementById('inquiryForm').addEventListener('submit', function (e) {
            e.preventDefault();

            const form = this;
            const submitBtn = document.getElementById('submitBtn');
            const btnText = document.getElementById('btnText');
            const formData = new FormData(form);

            submitBtn.disabled = true;
            btnText.innerText = "Dispatching Application...";

            fetch(form.action, {
                method: 'POST',
                headers: {
                    'X-Requested-With': 'XMLHttpRequest',
                    'Accept': 'application/json',
                    'X-CSRF-TOKEN': formData.get('_token')
                },
                body: formData
            })
            .then(async res => {
                const data = await res.json();
                if (!res.ok) {
                    // Laravel validation errors show kora
                    if (data.errors) {
                        const errorMsg = Object.values(data.errors).flat().join('\n');
                        throw new Error(errorMsg);
                    }
                    throw new Error(data.message || 'Server error occurred');
                }
                return data;
            })
            .then(data => {
                form.reset();
                submitBtn.disabled = false;
                btnText.innerText = "Lodge Application File";

                closeModal();
                showInstantSuccessModal(data.message || 'Application received successfully!');
            })
            .catch(err => {
                submitBtn.disabled = false;
                btnText.innerText = "Lodge Application File";
                alert(err.message || 'Please check your inputs and try again.');
            });
        });
